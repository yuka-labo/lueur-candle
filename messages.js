// ランダムにメッセージを選択
// - 60% 時間帯別
// - 20% 季節別
// - 20% 汎用
// ========================================
function getRandomMessage() {
  const data = getMessages();
  const roll = Math.random();

  let pool;
  let source;

  if (roll < 0.6) {
    // 時間帯別
    pool = data.messages;
    source = 'timeOfDay';
  } else if (roll < 0.8) {
    // 季節別
    pool = POEMS.seasonal[data.season] || [];
    source = 'seasonal';
  } else {
    // 汎用
    pool = POEMS.general;
    source = 'general';
  }

  // フォールバック
  if (!pool || pool.length === 0) {
    pool = POEMS.general;
    source = 'general';
  }

  const randomIndex = Math.floor(Math.random() * pool.length);
  const poem = pool[randomIndex];

  return {
    text: poem.text,
    author: poem.author,
    type: source,
    timeOfDay: data.timeOfDay,
  };
}
